def jsonl(path):
    with open(path) as f:
        return [json.loads(line) for line in f if line.strip()]


def pct(xs, p):
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(p * len(xs)))]


def us(x):
    """Formats microseconds for a table: µs below 1 ms, ms above."""
    if x < 1000:
        return f"{x:.0f}\\,\\textmu s"
    return f"{x / 1000:.1f}\\,ms"


def us_range(lo, hi):
    a, b = us(lo), us(hi)
    if a == b:
        return a
    unit = "\\,\\textmu s" if lo < 1000 and hi < 1000 else ("\\,ms" if lo >= 1000 else None)
    if unit and a.endswith(unit) and b.endswith(unit):
        return a[: -len(unit)] + "--" + b
    return a + "--" + b


def tex_id(s):
    return s.replace("_", "\\_")


def tex_attack_label(s):
    # This identifier is too long for the fixed-width appendix matrix. Keep
    # its exact spelling visible across two lines rather than overflowing.
    if s == "exec-py-preexisting-hardlink-secret":
        return (
            r"\shortstack[l]{\texttt{exec-py-preexisting-}"
            r"\\\texttt{hardlink-secret}}"
        )
    return f"\\texttt{{{tex_id(s)}}}"


def tex_text(s):
    """Escapes prose for LaTeX; spans in backticks are set in typewriter type."""
    out = []
    for i, part in enumerate(s.split("`")):
        if i % 2:
            out.append("\\texttt{" + escape(part).replace("-", "-{}") + "}")
        else:
            out.append(escape(part))
    return "".join(out)


def escape(s):
    for a, b in [("\\", "\\textbackslash{}"), ("_", "\\_"), ("%", "\\%"), ("&", "\\&"), ("#", "\\#"), ("$", "\\$"), ("~", "\\textasciitilde{}")]:
        s = s.replace(a, b)
    return s


def macro_name(s):
    out = []
    up = True
    for c in s:
        if c.isalpha():
            out.append(c.upper() if up else c)
            up = False
        else:
            up = True
    return "".join(out)


class Macros:
    def __init__(self):
        self.lines = ["% Generated by experiments/analyze.py. Do not edit."]

    def add(self, name, value):
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def write(self, path):
        path.write_text("\n".join(self.lines) + "\n")


def validate_security(rows, attacks):
    """Reject invalid, duplicate, or incomplete evidence before emitting files."""
    ids = [a["id"] for a in attacks]
    if len(set(ids)) != len(ids):
        raise ValueError("duplicate attack IDs")
    expected = {(s, i) for s in MAIN_SETUPS + [f"ZTAC-no-{d}" for d in DEFENSE_LABEL] for i in ids}
    seen = set()
    for r in rows:
        key = (r["setup"], r["id"])
        if r["outcome"] not in {"succeeded", "escalated", "blocked"}:
            raise ValueError(f"invalid security trial: {key}: {r['outcome']}")
        if key in seen:
            raise ValueError(f"duplicate security trial: {key}")
        seen.add(key)
    if seen != expected:
        raise ValueError(f"incomplete security matrix: missing {sorted(expected - seen)}, unexpected {sorted(seen - expected)}")


STAGE_KEYS = ["auth_us", "resolve_us", "policy_us", "execute_us", "audit_us"]


def paired_stages(row):
    """Means of paired components sum to mean client latency."""
    latencies, stages = row["latency_us"], row["stages"]
    if not latencies or len(latencies) != len(stages):
        raise ValueError("unpaired or empty stage samples")
    components = []
    for latency, stage in zip(latencies, stages):
        values = [stage[k] for k in STAGE_KEYS]
        broker_other = stage["total_us"] - sum(values)
        ipc = latency - stage["total_us"]
        if min(values + [broker_other, ipc]) < 0:
            raise ValueError("negative paired timing residual")
        components.append(values + [broker_other, ipc])
    return [statistics.mean(c[i] for c in components) for i in range(7)]


def security(res, out, m):
    rows = jsonl(res / "security.jsonl")
    attacks = json.load(open(res / "attacks.json"))
    validate_security(rows, attacks)
    ids = [a["id"] for a in attacks]
    by = {(r["setup"], r["id"]): r for r in rows}
    setups = list(OrderedDict.fromkeys(r["setup"] for r in rows))

    m.add("NumAttacks", len(ids))
    m.add("NumCategories", len(CATEGORY_LABEL))
    m.add("NumAblations", len(DEFENSE_LABEL))
    for cat in CATEGORY_LABEL:
        m.add("NumAttacks" + macro_name(cat), sum(1 for a in attacks if a["category"] == cat))
    for s in setups:
        c = Counter(by[(s, i)]["outcome"] for i in ids)
        key = macro_name(s.replace("ZTAC-no-", "no-").replace("+", "-and-"))
        for o in ["succeeded", "escalated", "blocked"]:
            m.add(f"Sec{key}{o.capitalize()}", c.get(o, 0))

    m.add("NumIncidents", len(INCIDENT_ATTACKS))
    for s in MAIN_SETUPS:
        c = Counter(by[(s, i)]["outcome"] for i in INCIDENT_ATTACKS)
        key = macro_name(s)
        for o in ["succeeded", "escalated", "blocked"]:
            m.add(f"Inc{key}{o.capitalize()}", c.get(o, 0))

    # Expected-versus-observed check for full ZTAC.
    mismatches = [a["id"] for a in attacks if by[("ZTAC", a["id"])]["outcome"] != a["expected"]]
    m.add("NumExpectationMismatches", len(mismatches))
    if mismatches:
        print("WARNING: outcome differs from expectation for", mismatches, file=sys.stderr)

    # Table: outcomes per category for the main setups.
    lines = [
        "\\begin{tabular}{@{}l r " + " ".join(["r"] * len(MAIN_SETUPS)) + "@{}}",
        "\\toprule",
        "Category & $n$ & " + " & ".join(SETUP_LABEL[s] for s in MAIN_SETUPS) + " \\\\",
        "\\midrule",
    ]

    def cell(s, subset):
        c = Counter(by[(s, i)]["outcome"] for i in subset)
        succ, esc = c.get("succeeded", 0), c.get("escalated", 0)
        text = f"{succ}"
        if esc:
            text += f"\\,/\\,{esc}"
        return text

    for cat in CATEGORY_LABEL:
        label = CATEGORY_SHORT[cat]
        subset = [a["id"] for a in attacks if a["category"] == cat]
        lines.append(f"{label} & {len(subset)} & " + " & ".join(cell(s, subset) for s in MAIN_SETUPS) + " \\\\")
    lines.append("\\midrule")
    lines.append(f"Total & {len(ids)} & " + " & ".join(cell(s, ids) for s in MAIN_SETUPS) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (out / "security_table.tex").write_text("\n".join(lines) + "\n")

    # Appendix matrix: every attack under every setup.
    sym = {"succeeded": "\\attS", "escalated": "\\attE", "blocked": "\\attB"}
    cols = MAIN_SETUPS + [s for s in setups if s.startswith("ZTAC-no-")]
    head = [SETUP_LABEL.get(s, "") for s in MAIN_SETUPS]
    head += ["\\rotatebox{90}{$-$" + DEFENSE_LABEL[s[len("ZTAC-no-"):]].replace("+", "+") + "}" for s in cols[len(MAIN_SETUPS):]]
    parts = {"a": ["filesystem", "exec"], "b": ["handoff", "network", "protocol", "approval", "direct"]}
    for part, cats in parts.items():
        lines = [
            "\\begin{tabular}{@{}l l " + "c" * len(cols) + "@{}}",
            "\\toprule",
            "Attack & Goal & " + " & ".join(head) + " \\\\",
            "\\midrule",
        ]
        for cat in cats:
            label = CATEGORY_LABEL[cat]
            lines.append(f"\\multicolumn{{{len(cols) + 2}}}{{@{{}}l}}{{\\textit{{{label}}}}} \\\\")
            for a in attacks:
                if a["category"] != cat:
                    continue
                row = [tex_attack_label(a["id"]), a["goal"]]
                row += [sym[by[(s, a["id"])]["outcome"]] for s in cols]
                lines.append(" & ".join(row) + " \\\\")
        lines += ["\\bottomrule", "\\end{tabular}"]
        (out / f"attack_matrix_{part}.tex").write_text("\n".join(lines) + "\n")

    # Attack descriptions for the appendix.
    for part, cats in parts.items():
        lines = ["\\begin{tabular}{@{}l >{\\raggedright\\arraybackslash}p{0.68\\linewidth}@{}}", "\\toprule", "Attack & Attempt \\\\", "\\midrule"]
        for cat in cats:
            label = CATEGORY_LABEL[cat]
            lines.append(f"\\multicolumn{{2}}{{@{{}}l}}{{\\textit{{{label}}}}} \\\\")
            for a in attacks:
                if a["category"] == cat:
                    lines.append(f"{tex_attack_label(a['id'])} & {tex_text(a['description'])} \\\\")
        lines += ["\\bottomrule", "\\end{tabular}"]
        (out / f"attack_list_{part}.tex").write_text("\n".join(lines) + "\n")

    # Outcome of every attack under every setup as \outcome{SETUP}{ATTACK},
    # for tables in the text that discuss individual attacks.
    sym_of = {"succeeded": "\\attS", "escalated": "\\attE", "blocked": "\\attB"}
    lines = ["% Generated by experiments/analyze.py. Do not edit."]
    for s in setups:
        short = SETUP_LABEL.get(s, s).replace("Z$_\\text{broker}$", "Zbroker")
        for i in ids:
            lines.append(f"\\expandafter\\def\\csname ztacout@{short}@{i}\\endcsname{{{sym_of[by[(s, i)]['outcome']]}}}")
    (out / "outcomes.tex").write_text("\n".join(lines) + "\n")

    # Figure data: outcome counts per configuration, main setups then ablations.
    fig = ["label succeeded escalated blocked"]
    for s in MAIN_SETUPS + [x for x in setups if x.startswith("ZTAC-no-")]:
        c = Counter(by[(s, i)]["outcome"] for i in ids)
        if s.startswith("ZTAC-no-"):
            label = "{$-$" + DEFENSE_LABEL[s[len("ZTAC-no-"):]].replace("+", "\\,+\\,") + "}"
        else:
            label = "{" + SETUP_LABEL[s] + "}"
        fig.append(f"{label} {c.get('succeeded', 0)} {c.get('escalated', 0)} {c.get('blocked', 0)}")
    (out / "outcomes.dat").write_text("\n".join(fig) + "\n")

    # Ablation: which attacks each removed defense lets through.
    full = {i: by[("ZTAC", i)]["outcome"] for i in ids}
    lines = ["\\begin{tabular}{@{}l c >{\\raggedright\\arraybackslash}p{0.62\\linewidth}@{}}", "\\toprule", "Removed defense & $\\Delta$ & Attacks that now succeed \\\\", "\\midrule"]
    for d, label in DEFENSE_LABEL.items():
        s = f"ZTAC-no-{d}"
        if s not in setups:
            continue
        newly = [i for i in ids if by[(s, i)]["outcome"] == "succeeded" and full[i] != "succeeded"]
        m.add("Abl" + macro_name(d.replace("+", "-and-")) + "Count", len(newly))
        text = ", ".join(f"\\texttt{{{tex_id(i)}}}" for i in newly) if newly else "none"
        lines.append(f"{label} & +{len(newly)} & {text} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (out / "ablation_table.tex").write_text("\n".join(lines) + "\n")
    return setups


def validate_workload(rows, label):
    if not rows:
        raise ValueError(f"empty {label} evidence")
    by = OrderedDict()
    for r in rows:
        if not r.get("valid", False):
            raise ValueError(f"invalid {label}: {r['setup']}/{r['id']}")
        if r["id"] in by.setdefault(r["setup"], {}):
            raise ValueError(f"duplicate {label}: {r['setup']}/{r['id']}")
        by[r["setup"]][r["id"]] = r
    expected_setups = set(MAIN_SETUPS + [f"ZTAC-no-{d}" for d in DEFENSE_LABEL])
    if set(by) != expected_setups:
        raise ValueError(f"incomplete {label} setup matrix")
    ids = set(by["ZTAC"])
    if any(set(group) != ids for group in by.values()):
        raise ValueError(f"unequal {label} IDs across setups")
    return by


def utility(res, out, m, setups):
    by_setup = validate_workload(jsonl(res / "utility.jsonl"), "operations")
    workflows = validate_workload(jsonl(res / "workflows.jsonl"), "workflows")
    n, nw = len(by_setup["ZTAC"]), len(workflows["ZTAC"])
    m.add("NumOperations", n)
    m.add("NumWorkflows", nw)
    for s, rs in by_setup.items():
        key = macro_name(s.replace("ZTAC-no-", "no-").replace("+", "-and-"))
        completed = sum(r["completed"] for r in rs.values())
        m.add(f"Util{key}Completed", completed)
        m.add(f"Util{key}Failed", n-completed)
        m.add(f"Util{key}Prompts", sum(r["prompts"] for r in rs.values()))
        ws = list(workflows[s].values())
        done = sum(w["completed"] for w in ws)
        m.add(f"Workflow{key}Completed", done)
        m.add(f"Workflow{key}Failed", nw-done)
        m.add(f"Workflow{key}Prompts", sum(w["prompts"] for w in ws))
    kinds = Counter(r["kind"] for r in by_setup["ZTAC"].values())
    for k, v in kinds.items():
        m.add("NumOperations" + macro_name(k), v)
    for name, predicate in [("UtilPromptedOperations", lambda r: r["prompts"]),
                            ("UtilFailedOperations", lambda r: not r["completed"])]:
        m.add(name, ", ".join(f"\\texttt{{{tex_id(r['id'])}}}" for r in by_setup["ZTAC"].values() if predicate(r)))
    m.add("WorkflowFailedNames", ", ".join(f"\\texttt{{{tex_id(w['id'])}}}" for w in workflows["ZTAC"].values() if not w["completed"]))
    lines = [r"\begin{tabular}{@{}l r r r@{}}", r"\toprule",
             r"Configuration & Operations & Prompts & Workflows \\", r"\midrule"]
    for s in MAIN_SETUPS:
        ops, ws = list(by_setup[s].values()), list(workflows[s].values())
        lines.append(f"{SETUP_LABEL[s]} & {sum(r['completed'] for r in ops)}/{n} & {sum(r['prompts'] for r in ops)} & {sum(w['completed'] for w in ws)}/{nw} " + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (out / "utility_table.tex").write_text("\n".join(lines) + "\n")
    lines = [r"\begin{tabular}{@{}l c c c c c@{}}", r"\toprule",
             "Workflow & " + " & ".join(SETUP_LABEL[s] for s in MAIN_SETUPS) + r" \\", r"\midrule"]
    for wid in workflows["ZTAC"]:
        lines.append(tex_text(wid) + " & " + " & ".join("yes" if workflows[s][wid]["completed"] else "no" for s in MAIN_SETUPS) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (out / "workflow_table.tex").write_text("\n".join(lines) + "\n")


def extra_experiments(res, out, m):
    agreement = jsonl(res / "agreement.jsonl")
    if not agreement or not all(r["passed"] for r in agreement):
        raise ValueError("policy agreement evidence missing or failed")
    m.add("NumAgreementChecks", len(agreement))
    m.add("NumAgreementDifferences", sum(r["broker"] == "allow" and not r["sandbox_permitted"] or
                                          r["broker"] != "allow" and r["sandbox_permitted"] for r in agreement))
    rows = jsonl(res / "race.jsonl")
    groups = OrderedDict()
    seen = set()
    for row in rows:
        trial, r = row["trial"], row["result"]
        key = (r["setup"], trial)
        if key in seen or r["outcome"] == "invalid":
            raise ValueError(f"invalid/duplicate repeated race trial {key}")
        seen.add(key)
        groups.setdefault(r["setup"], []).append(row)
    expected = {"B0-unconfined", "ZTAC", "ZTAC-no-fd_walk", "ZTAC-no-no_fork", "ZTAC-no-fd_walk+no_fork"}
    if set(groups) != expected:
        raise ValueError("incomplete race configurations")
    n = len(groups["ZTAC"])
    if not n or any({r["trial"] for r in g} != set(range(1,n+1)) for g in groups.values()):
        raise ValueError("incomplete repeated race trials")
    m.add("NumRaceTrials", n)
    lines = [r"\begin{tabular}{@{}l r r@{}}", r"\toprule", r"Configuration & Successes & Trials \\", r"\midrule"]
    for s, g in groups.items():
        count = sum(row["result"]["outcome"] == "succeeded" for row in g)
        key = macro_name(s.replace("ZTAC-no-", "no-").replace("+", "-and-"))
        m.add(f"Race{key}Succeeded", count)
        label = SETUP_LABEL.get(s, "$-$" + DEFENSE_LABEL[s[len("ZTAC-no-"):]]) if s not in SETUP_LABEL else SETUP_LABEL[s]
        lines.append(f"{label} & {count} & {n} " + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (out / "race_table.tex").write_text("\n".join(lines)+"\n")


def bench(res, out, m, extra):
    rows = jsonl(res / "latency.jsonl")
    get = {(r["op"], r["setup"]): r for r in rows}
    runs = [get]
    for e in extra:
        runs.append({(r["op"], r["setup"]): r for r in jsonl(Path(e) / "latency.jsonl")})

    multi = len(runs) > 1
    lines = [
        "\\begin{tabular}{@{}l r r r r" + (" r" if multi else "") + "@{}}",
        "\\toprule",
        "Operation & Direct & ZTAC & p99 & Added" + (" & Range" if multi else "") + " \\\\",
        "\\midrule",
    ]
    fig_direct, fig_ztac = [], []
    for op, label in OP_LABEL.items():
        d = get[(op, "direct")]["latency_us"]
        z = get[(op, "bench-ztac")]["latency_us"]
        dm, zm = statistics.median(d), statistics.median(z)
        # ping has no direct counterpart; its broker latency is all overhead.
        dtxt = "--" if op == "ping" else us(dm)
        row = f"{label} & {dtxt} & {us(zm)} & {us(pct(z, 0.99))} & {us(zm - dm)}"
        key = macro_name(op)
        m.add(f"Lat{key}Direct", us(dm))
        m.add(f"Lat{key}Ztac", us(zm))
        m.add(f"Lat{key}Added", us(zm - dm))
        if op != "ping":
            m.add(f"Lat{key}Ratio", f"{zm / dm:.1f}")
        fig_direct.append((op, max(dm, 1)))
        fig_ztac.append((op, zm))
        if multi:
            meds = [statistics.median(r[(op, "bench-ztac")]["latency_us"]) for r in runs]
            m.add(f"Lat{key}ZtacMin", us(min(meds)))
            m.add(f"Lat{key}ZtacMax", us(max(meds)))
            row += f" & {us_range(min(meds), max(meds))}"
        lines.append(row + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (out / "latency_table.tex").write_text("\n".join(lines) + "\n")
    m.add("NumBenchRuns", len(runs))

    # Stacked means from paired requests preserve the end-to-end total.
    max_stage = 0
    lines = ["op auth resolve policy execute audit other ipc"]
    for op in ["ping", "fs_read_4k", "net_get"]:
        values = paired_stages(get[(op, "bench-ztac")])
        max_stage = max(max_stage, sum(values))
        lines.append(op + " " + " ".join(f"{v:.3f}" for v in values))
        if op == "ping":
            for name, value in [("StageAuth", values[0]), ("StageAudit", values[4]),
                                ("StageResolvePolicy", values[1] + values[2]),
                                ("StageOther", values[5]), ("StageIpc", values[6])]:
                m.add(name, f"{value:.0f}")
    (out / "stages.dat").write_text("\n".join(lines) + "\n")
    m.add("StageAxisMax", (int(max_stage / 100) + 1) * 100)

    with open(out / "latency.dat", "w") as f:
        f.write("op idx direct ztac\n")
        for i, ((op, d), (_, z)) in enumerate(zip(fig_direct, fig_ztac)):
            f.write(f"{op} {i} {d:.1f} {z:.1f}\n")

    # Exec sandbox cost, isolated.
    for op in ["exec_echo", "exec_git_status"]:
        with_sb = statistics.median(get[(op, "bench-ztac")]["latency_us"])
        without = statistics.median(get[(op, "bench-no-exec-sandbox")]["latency_us"])
        m.add("SbCost" + macro_name(op), us(with_sb - without))
        m.add("NoSb" + macro_name(op), us(without))
    launch = {r["setup"]: statistics.median(r["latency_us"]) for r in rows if r["op"] == "cell_launch"}
    m.add("LaunchUnsandboxed", us(launch["unsandboxed"]))
    m.add("LaunchSandboxed", us(launch["sandboxed"]))
    m.add("LaunchAdded", us(launch["sandboxed"] - launch["unsandboxed"]))

    tput = json.load(open(res / "throughput.json"))
    m.add("TputOne", f"{round(tput[0]['per_second'], -2):,.0f}".replace(",", "{,}"))
    m.add("TputPeak", f"{round(max(t['per_second'] for t in tput), -2):,.0f}".replace(",", "{,}"))
    m.add("TputMaxClients", max(t["clients"] for t in tput))
    av = json.load(open(res / "audit_verify.json"))
    m.add("AuditVerifyRecords", f"{av['records']:,}".replace(",", "{,}"))
    m.add("AuditVerifyRate", f"{round(av['records'] / av['seconds'], -3):,.0f}".replace(",", "{,}"))


def tcb_lines(root, m):
    """Non-blank, non-comment lines outside test modules, per crate. Code
    that runs only on the untrusted side (the request client and the probe
    used by the evaluation) is not part of the trusted base."""
    untrusted = {"client.rs", "ztac-client.rs", "ztac-probe.rs"}
    total = 0
    for crate in ["core", "broker", "cell"]:
        n = 0
        for f in sorted((root / "crates" / crate / "src").rglob("*.rs")):
            if f.name in untrusted:
                continue
            for line in f.read_text().split("#[cfg(test)]")[0].splitlines():
                t = line.strip()
                if t and not t.startswith("//"):
                    n += 1
        m.add("Loc" + macro_name(crate), f"{n:,}".replace(",", "{,}"))
        total += n
    m.add("LocTcb", f"{total:,}".replace(",", "{,}"))
    m.add("LocTcbK", f"{total / 1000:.1f}")


def environment(res, m):
    env = dict(
        line.split(": ", 1) for line in (res / "environment.txt").read_text().splitlines() if ": " in line
    )
    # "Mac18,5 Apple M6 24 GiB" -> "Mac18,5 with an Apple M6 and 24\,GiB of memory"
    host = env.get("host", "")
    hm = re.match(r"(\S+) (.+) (\d+) GiB$", host)
    if hm:
        host = f"{hm.group(1)} with an {hm.group(2)} and {hm.group(3)}\\,GiB of memory"
    m.add("EnvHost", host.replace("_", "\\_"))
    m.add("EnvOs", env.get("os", ""))
    m.add("EnvGit", env.get("git", "").replace("git version ", ""))
    m.add("EnvPython", env.get("python", "").replace("Python ", ""))


def main():
    res = Path(sys.argv[1])
    out = Path(sys.argv[2])
    extra = sys.argv[3:]
    validate_security(jsonl(res / "security.jsonl"), json.load(open(res / "attacks.json")))
    for directory in [res] + [Path(e) for e in extra]:
        for row in jsonl(directory / "latency.jsonl"):
            if row["setup"] == "bench-ztac":
                paired_stages(row)
    validate_workload(jsonl(res / "utility.jsonl"), "operations")
    validate_workload(jsonl(res / "workflows.jsonl"), "workflows")
    # Validate auxiliary experiments in a temporary, isolated output before
    # overwriting the paper's current generated tables.
    import tempfile
    with tempfile.TemporaryDirectory() as check_dir:
        extra_experiments(res, Path(check_dir), Macros())
    out.mkdir(parents=True, exist_ok=True)
    m = Macros()
    setups = security(res, out, m)
    utility(res, out, m, setups)
    extra_experiments(res, out, m)
    bench(res, out, m, extra)
    environment(res, m)
    tcb_lines(Path(__file__).resolve().parent.parent, m)
    m.write(out / "numbers.tex")
    print(f"wrote tables and macros to {out}")


